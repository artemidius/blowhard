@Composable
internal fun MeetingNoteScreen(state: MeetingNoteUiState, onAction: (MeetingNoteAction) -> Unit, onBack: () -> Unit) {
    Column(Modifier.fillMaxSize().background(MaterialTheme.colorScheme.background)) {
        MeetingNoteHeader(state, onAction, onBack)
        HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant)
        val draft = state.draft
        if (draft == null) {
            Column(Modifier.padding(32.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                Text("No generated note", style = MaterialTheme.typography.headlineSmall)
                Text(
                    state.notice.label(),
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        } else {
            MeetingNoteEditor(draft, state, onAction)
        }
    }
    MeetingNoteOverlays(state, onAction)
}

@Composable
private fun MeetingNoteOverlays(state: MeetingNoteUiState, onAction: (MeetingNoteAction) -> Unit) {
    state.export?.let { export ->
        AlertDialog(
            onDismissRequest = { onAction(MeetingNoteAction.ExportDismissed) },
            title = { Text(export.suggestedFileName) },
            text = {
                Text(
                    export.content,
                    modifier = Modifier.verticalScroll(rememberScrollState()),
                    fontFamily = FontFamily.Monospace,
                )
            },
            confirmButton = {
                TextButton(onClick = { onAction(MeetingNoteAction.ExportDismissed) }) { Text("Close") }
            },
        )
    }
    state.approval?.let { approval ->
        ProposedMeetingNoteApprovalDialog(
            state = approval,
            onApprove = { onAction(MeetingNoteAction.ApproveWrite) },
            onDeny = { onAction(MeetingNoteAction.DenyWrite) },
            onDismiss = { onAction(MeetingNoteAction.ApprovalDismissed) },
        )
    }
}

@Composable
private fun MeetingNoteHeader(state: MeetingNoteUiState, onAction: (MeetingNoteAction) -> Unit, onBack: () -> Unit) {
    Row(
        modifier = Modifier.fillMaxWidth().padding(horizontal = 20.dp, vertical = 16.dp),
        horizontalArrangement = Arrangement.spacedBy(12.dp),
    ) {
        TextButton(onClick = onBack) { Text("Back") }
        Column(Modifier.weight(1f)) {
            Text(
                "Meeting note",
                modifier = Modifier.semantics { heading() },
                style = MaterialTheme.typography.titleLarge,
            )
            Text(
                state.note?.let { "Generated by ${it.modelId} · revision ${it.revision}" }
                    ?: "Structured output with source evidence",
                style = MaterialTheme.typography.bodySmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
        TextButton(
            enabled = state.note != null && !state.isBusy,
            onClick = { onAction(MeetingNoteAction.Export(MeetingNoteExportFormat.JSON)) },
        ) { Text("JSON") }
        TextButton(
            enabled = state.note != null && !state.isBusy,
            onClick = { onAction(MeetingNoteAction.Export(MeetingNoteExportFormat.MARKDOWN)) },
        ) { Text("Markdown") }
        Button(enabled = state.note != null && !state.isBusy, onClick = { onAction(MeetingNoteAction.Save) }) {
            Text(if (state.isBusy) "Working…" else "Save edit")
        }
        Button(
            enabled = state.note != null && !state.isBusy,
            onClick = { onAction(MeetingNoteAction.ProposeWrite) },
        ) { Text("Approve local copy") }
    }
}

@Composable
private fun MeetingNoteEditor(
    draft: MeetingNoteDraft,
    state: MeetingNoteUiState,
    onAction: (MeetingNoteAction) -> Unit,
) {
    Column(
        Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(24.dp),
        verticalArrangement = Arrangement.spacedBy(20.dp),
    ) {
        state.notice?.let { Text(it.label(), color = MaterialTheme.colorScheme.tertiary) }
        OutlinedTextField(
            value = draft.title,
            onValueChange = { onAction(MeetingNoteAction.TitleChanged(it)) },
            modifier = Modifier.fillMaxWidth(),
            label = { Text("Title") },
        )
        MeetingDecisions(draft, onAction)
        MeetingActions(draft, onAction)
    }
}

@Composable
private fun MeetingDecisions(draft: MeetingNoteDraft, onAction: (MeetingNoteAction) -> Unit) {
    Text("Decisions", style = MaterialTheme.typography.titleMedium)
    draft.decisions.forEachIndexed { index, decision ->
        OutlinedTextField(
            value = decision.summary,
            onValueChange = { onAction(MeetingNoteAction.DecisionChanged(index, it)) },
            modifier = Modifier.fillMaxWidth(),
            label = { Text("Decision ${index + 1}") },
            supportingText = { Text(decision.sources.evidenceLabel()) },
        )
    }
}

@Composable
private fun MeetingActions(draft: MeetingNoteDraft, onAction: (MeetingNoteAction) -> Unit) {
    Text("Action items", style = MaterialTheme.typography.titleMedium)
    draft.actionItems.forEachIndexed { index, item ->
        Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
            OutlinedTextField(
                value = item.description,
                onValueChange = { onAction(MeetingNoteAction.ActionDescriptionChanged(index, it)) },
                modifier = Modifier.fillMaxWidth(),
                label = { Text("Action ${index + 1}") },
                supportingText = { Text(item.sources.evidenceLabel()) },
            )
            Row(horizontalArrangement = Arrangement.spacedBy(12.dp)) {
                OutlinedTextField(
                    value = item.owner,
                    onValueChange = { onAction(MeetingNoteAction.ActionOwnerChanged(index, it)) },
                    modifier = Modifier.weight(1f),
                    label = { Text("Owner (optional)") },
                )
                OutlinedTextField(
                    value = item.dueDate,
                    onValueChange = { onAction(MeetingNoteAction.ActionDueDateChanged(index, it)) },
                    modifier = Modifier.weight(1f),
                    label = { Text("Due date (YYYY-MM-DD)") },
                )
            }
        }
    }
}

private fun List<io.github.artemidius.blowhard.core.api.MeetingNoteSourceReference>.evidenceLabel(): String =
    joinToString(" · ") { "Page ${it.pageIndex + 1}: ${it.excerpt}" }

private fun MeetingNoteNotice?.label(): String = when (this) {
    MeetingNoteNotice.Saved -> "Edit saved locally; generated content remains preserved."
    MeetingNoteNotice.InvalidEdit -> "Review required fields and use a valid YYYY-MM-DD date."
    is MeetingNoteNotice.GenerationRejected -> "Generation unavailable: ${label.lowercase().replace('_', ' ')}."
    MeetingNoteNotice.OperationUnavailable -> "The operation could not be completed safely."
    null -> "Generate a note from an extracted document in the document workbench."
}
